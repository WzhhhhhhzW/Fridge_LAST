static void boot_fail_closed(void)
{
    /*
     * Do not refresh the auto-start IWDT here. A crypto initialization
     * failure or the absence of an authenticated image must never fall
     * through into an unverified application.
     */
    while (1)
    {
        __WFI();
    }
}

/*******************************************************************************************************************//**
 * main() is generated by the RA Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
    mbedtls_platform_context crypto_context = {0};
    struct boot_rsp          boot_response  = {0};
    FIH_DECLARE(boot_result, FIH_FAILURE);

    ota_boot_watchdog_refresh();

    /* Initialize the RA6M5 SCE9-backed MbedTLS port before verification. */
    if (0 != mbedtls_platform_setup(&crypto_context))
    {
        boot_fail_closed();
    }

    ota_boot_watchdog_refresh();

    /* Authenticate the selected Direct XIP image before entering it. */
    FIH_CALL(boot_go, boot_result, &boot_response);
    if (FIH_NOT_EQ(boot_result, FIH_SUCCESS))
    {
        boot_fail_closed();
    }

    if (FSP_SUCCESS != ota_boot_trial_process(&boot_response))
    {
        boot_fail_closed();
    }

    ota_boot_watchdog_refresh();
    RM_MCUBOOT_PORT_BootApp(&boot_response);

#if BSP_TZ_SECURE_BUILD
    /* Enter non-secure code */
    R_BSP_NonSecureEnter();
#endif

    boot_fail_closed();
}

/*******************************************************************************************************************//**
 * This function is called at various points during the startup process.  This implementation uses the event that is
 * called right before main() to set up the pins.
 *
 * @param[in]  event    Where at in the start up process the code is currently at
 **********************************************************************************************************************/
void R_BSP_WarmStart(bsp_warm_start_event_t event)
{
    if (BSP_WARM_START_RESET == event)
    {
#if BSP_FEATURE_FLASH_LP_VERSION != 0

        /* Enable reading from data flash. */
        R_FACI_LP->DFLCTL = 1U;

        /* Would normally have to wait tDSTOP(6us) for data flash recovery. Placing the enable here, before clock and
         * C runtime initialization, should negate the need for a delay since the initialization will typically take more than 6us. */
#endif
    }

    if (BSP_WARM_START_POST_C == event)
    {
        /* C runtime environment and system clocks are setup. */

        /* Configure pins. */
        R_IOPORT_Open (&IOPORT_CFG_CTRL, &IOPORT_CFG_NAME);

#if BSP_CFG_SDRAM_ENABLED

        /* Setup SDRAM and initialize it. Must configure pins first. */
        R_BSP_SdramInit(true);
#endif
    }
}

