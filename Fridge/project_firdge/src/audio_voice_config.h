#ifndef AUDIO_VOICE_CONFIG_H_
#define AUDIO_VOICE_CONFIG_H_

/*
 * Set this to the same random value as FRIDGE_AUDIO_TOKEN in
 * /etc/fridge-deepseek.env.  It is kept outside generated FSP files so
 * Generate Project Content will not overwrite it.
 */
#define AUDIO_VOICE_DEVICE_TOKEN    "STVJM8PSqh8OJWP9hUP8Ie5UJ4vIrOGrGRRrRN-_nZ8"

/*
 * Local Edge Impulse wake-word switch.
 * 0: do not initialize the model and do not run continuous KWS capture.
 *    P000 and the Flag=2 independent 0xC2 record button remain available.
 * 1: enable the local nihao_xiaou wake-word listener.
 */
#define AUDIO_VOICE_ENABLE_KWS      (0)

/*
 * MAX98357A SD_MODE control.  P311 is generated by FSP as a GPIO output with
 * an initial low level.  Keep a physical 10 kOhm pull-down on SD_MODE so the
 * amplifier stays shut down during reset and while the MCU is unpowered.
 */
#define AUDIO_AMP_SD_PIN            BSP_IO_PORT_03_PIN_11

#endif /* AUDIO_VOICE_CONFIG_H_ */
